//! MCP server: the tools clients call to work on the notes.

use rmcp::{
    ServerHandler,
    handler::server::{tool::ToolRouter, wrapper::Parameters},
    model::{Implementation, ServerCapabilities, ServerConfig},
    schemars::{self, JsonSchema},
    serde::Deserialize,
    tool, tool_handler, tool_router,
};

use crate::vault::Vault;

/// Streamable HTTP transport, mounted by the server.
pub(crate) mod http;

/// What every tool returns: the answer as text, or the error for the model.
type Answer = Result<String, String>;

/// Arguments of the tools that take one note.
#[derive(Debug, Deserialize, JsonSchema)]
#[serde(crate = "rmcp::serde")]
pub(crate) struct NoteArgs {
    /// Path of the note, relative to the vault, like `rust/cheatsheet.md`. See `list_notes`.
    note: String,
}

/// Arguments of `add_note`.
#[derive(Debug, Deserialize, JsonSchema)]
#[serde(crate = "rmcp::serde")]
pub(crate) struct AddArgs {
    /// Path of the new note, relative to the vault, like `rust/cheatsheet.md`.
    /// Missing folders are created.
    note: String,
    /// The note's Markdown content.
    content: String,
}

/// Arguments of `update_note`.
#[derive(Debug, Deserialize, JsonSchema)]
#[serde(crate = "rmcp::serde")]
pub(crate) struct UpdateArgs {
    /// Path of the note, relative to the vault, like `rust/cheatsheet.md`.
    note: String,
    /// Text to replace, copied exactly from the note, found there exactly once.
    old_text: String,
    /// Text to put in its place; empty deletes `old_text`.
    new_text: String,
}

/// MCP server: each `#[tool]` method below is a tool clients can call.
#[derive(Debug, Clone)]
pub(crate) struct Server {
    /// The notes the tools work on.
    vault: Vault,
    /// Generated by `#[tool_router]`.
    tool_router: ToolRouter<Self>,
}

#[tool_router]
impl Server {
    /// Tools over `vault`.
    pub(crate) fn new(vault: Vault) -> Self {
        Self {
            vault,
            tool_router: Self::tool_router(),
        }
    }

    /// Lists notes.
    #[tool(
        description = "List the vault's notes, one path per line, like `rust/cheatsheet.md`. Each note is usually one subject.",
        annotations(read_only_hint = true)
    )]
    async fn list_notes(&self) -> Answer {
        let notes = self.vault.list().map_err(|error| error.to_string())?;
        if notes.is_empty() {
            return Ok(String::from("The vault has no notes yet."));
        }
        Ok(notes.join("\n"))
    }

    /// Reads a note.
    #[tool(
        description = "Read a note's full Markdown content. Read a note before changing it.",
        annotations(read_only_hint = true)
    )]
    async fn read_note(&self, Parameters(args): Parameters<NoteArgs>) -> Answer {
        self.vault
            .read(&args.note)
            .map_err(|error| error.to_string())
    }

    /// Adds a note.
    #[tool(
        description = "Create a new Markdown note. Fails if the note already exists: then use `update_note`.",
        annotations(destructive_hint = false, idempotent_hint = false)
    )]
    async fn add_note(&self, Parameters(args): Parameters<AddArgs>) -> Answer {
        self.vault
            .create(&args.note, &args.content)
            .map_err(|error| error.to_string())?;
        Ok(format!("Created `{}`.", args.note))
    }

    /// Changes a note.
    #[tool(
        description = "Change a note: replace `old_text`, copied exactly from the note and found there once, with `new_text`. Read the note first. To rewrite it all, pass its whole content as `old_text`.",
        annotations(destructive_hint = true, idempotent_hint = false)
    )]
    async fn update_note(&self, Parameters(args): Parameters<UpdateArgs>) -> Answer {
        self.vault
            .edit(&args.note, &args.old_text, &args.new_text)
            .map_err(|error| error.to_string())?;
        Ok(format!("Updated `{}`.", args.note))
    }

    /// Deletes a note.
    #[tool(
        description = "Delete a note. It can't be undone from here: ask the user first.",
        annotations(destructive_hint = true, idempotent_hint = true)
    )]
    async fn delete_note(&self, Parameters(args): Parameters<NoteArgs>) -> Answer {
        self.vault
            .delete(&args.note)
            .map_err(|error| error.to_string())?;
        Ok(format!("Deleted `{}`.", args.note))
    }
}

#[allow(clippy::unused_async_trait_impl)]
#[tool_handler(router = self.tool_router)]
impl ServerHandler for Server {
    fn get_info(&self) -> ServerConfig {
        ServerConfig::new(ServerCapabilities::builder().enable_tools().build())
            .with_server_info(Implementation::new(
                env!("CARGO_PKG_NAME"),
                env!("CARGO_PKG_VERSION"),
            ))
            .with_instructions(env!("CARGO_PKG_DESCRIPTION"))
    }
}

#[cfg(test)]
mod tests {
    use std::fs;

    use pretty_assertions::assert_eq;

    use super::*;
    use crate::prelude::Result;

    /// A server over a fresh vault unique to `test`, holding `rust/cheatsheet.md`.
    fn server(test: &str) -> Result<Server> {
        let root = std::env::temp_dir().join(format!(
            "{}-{}-mcp-{test}",
            env!("CARGO_PKG_NAME"),
            std::process::id()
        ));
        fs::create_dir_all(root.join("rust"))?;
        fs::write(root.join("rust/cheatsheet.md"), "# Rust\n")?;
        Ok(Server::new(Vault::open(&root)?))
    }

    /// `args` for a tool that takes one note.
    fn note(path: &str) -> Parameters<NoteArgs> {
        Parameters(NoteArgs {
            note: path.to_owned(),
        })
    }

    #[tokio::test]
    async fn list_notes_gives_one_path_per_line() -> Result<()> {
        let server = server("list")?;
        assert_eq!(
            server.list_notes().await,
            Ok(String::from("rust/cheatsheet.md"))
        );
        Ok(())
    }

    #[tokio::test]
    async fn read_note_gives_the_content() -> Result<()> {
        let server = server("read")?;
        assert_eq!(
            server.read_note(note("rust/cheatsheet.md")).await,
            Ok(String::from("# Rust\n"))
        );
        Ok(())
    }

    #[tokio::test]
    async fn read_note_explains_a_bad_path() -> Result<()> {
        let server = server("bad")?;
        let answer = server.read_note(note("../secret.md")).await;
        assert!(
            answer
                .as_ref()
                .is_err_and(|error| error.contains("relative path")),
            "{answer:?}"
        );
        Ok(())
    }

    #[tokio::test]
    async fn add_update_delete_round_trip() -> Result<()> {
        let server = server("write")?;
        let add = |note: &str, content: &str| {
            Parameters(AddArgs {
                note: note.to_owned(),
                content: content.to_owned(),
            })
        };
        let update = |old: &str, new: &str| {
            Parameters(UpdateArgs {
                note: String::from("ideas.md"),
                old_text: old.to_owned(),
                new_text: new.to_owned(),
            })
        };

        assert_eq!(
            server.add_note(add("ideas.md", "- a\n")).await,
            Ok(String::from("Created `ideas.md`."))
        );
        let again = server.add_note(add("ideas.md", "")).await;
        assert!(
            again
                .as_ref()
                .is_err_and(|error| error.contains("update_note")),
            "{again:?}"
        );

        assert!(server.update_note(update("- a", "- b")).await.is_ok());
        assert_eq!(
            server.read_note(note("ideas.md")).await,
            Ok(String::from("- b\n"))
        );
        let missing = server.update_note(update("- z", "- y")).await;
        assert!(
            missing
                .as_ref()
                .is_err_and(|error| error.contains("not in")),
            "{missing:?}"
        );

        assert!(server.delete_note(note("ideas.md")).await.is_ok());
        assert_eq!(
            server.list_notes().await,
            Ok(String::from("rust/cheatsheet.md"))
        );
        Ok(())
    }

    #[test]
    fn info_advertises_tools() -> Result<()> {
        let info = server("info")?.get_info();
        assert!(info.capabilities.tools.is_some());
        assert_eq!(info.server_info.name, env!("CARGO_PKG_NAME"));
        Ok(())
    }
}
